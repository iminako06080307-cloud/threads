// 生成をJSONで返させるための指示 + 出力スキーマ
export function buildGenerationPrompt(params: {
  formatId: string;
  topic: string;
}): string {
  const format = getFormat(params.formatId);
  const topicLine = params.topic.trim()
    ? `お題・テーマ: ${params.topic.trim()}`
    : "お題: おまかせ (40〜60代女性に刺さる、このフォーマットの鉄板テーマを自分で選ぶ)";

  return `${topicLine}
フォーマット: ${format.label} — ${format.description}

このフォーマットの構成ルール:
${format.structure}

上記とシステムで指定した型・トーンに沿って、メイン投稿1件 + 連投${format.threadCount - 1}件程度のスレッドを作ってください。
各投稿は必ず${THREADS_MAX_CHARS}文字以内。ターゲットは40〜60代女性。
必ず次のJSONのみを出力してください (前後に説明文やコードブロックの記号を付けない):

{
  "text": "メイン投稿の本文 (思い込みの代弁→結論、から始める。${THREADS_MAX_CHARS}文字以内)",
  "thread": ["連投2件目の本文", "連投3件目の本文", "..."],
  "hashtags": "#ダイエット #糖質ダイエット のように1〜3個 (任意)"
}`;
}

// ---------- システムプロンプト (共通 + スタイル) ----------
const SHARED_SYSTEM_PROMPT = `あなたはThreadsでダイエット情報を発信します。
読者は40〜60代の女性で、代謝の低下やリバウンド、過去の食事制限の失敗に悩む人が中心です。

【最重要: 誠実さのルール】
- 発信者は「本来は太りやすい体質だが、日々の習慣で太りにくい生活を続けて体型を維持している」人。
  この体質と維持の習慣は本人の実体験なので正直に語ってよい。
- ただし「私は◯kg痩せた」という減量ドラマは無いので、ビフォーアフターは絶対に捏造しない。
- 他人の体験・写真を自分のものとして語らない。
- 効果や結果を保証しない (「絶対」「必ず痩せる」等は使わない)。「〜しやすい」「傾向がある」と誠実に書く。

【共通ルール】
- ターゲットに寄り添い、責めない。更年期・代謝低下・体力など年代の悩みに理解を示す。
- 難しい栄養用語は噛み砕く。一文を短く、詰め込みすぎず、読みやすく。
- Threadsは1投稿${THREADS_MAX_CHARS}文字まで。超える内容は連投(スレッド)に分ける。
- 極端な断食や危険な減量、医療的に断定的な表現をしない。健康的で持続可能な範囲にする。
- 実在の商品名・書籍名・他人の投稿文をそのまま使わない (自分の言葉で書く)。`;

export function buildSystemPrompt(styleId: string): string {
  const style = getStyle(styleId);
  return `${SHARED_SYSTEM_PROMPT}\n\n${style.prompt}`;
}

// 後方互換: 既定スタイルのシステムプロンプト
export const DIET_SYSTEM_PROMPT = buildSystemPrompt("EXPERT");

// ---------- ユーザープロンプト ----------
export function buildGenerationPrompt(params: {
  formatId: string;
  topic: string;
}): string {
  const format = getFormat(params.formatId);
  const topicLine = params.topic.trim()
    ? `お題・テーマ: ${params.topic.trim()}`
    : "お題: おまかせ (40〜60代女性に刺さる、このフォーマットの鉄板テーマを自分で選ぶ)";

  return `${topicLine}
フォーマット: ${format.label} — ${format.description}

このフォーマットの構成ルール:
${format.structure}

上記と、システムで指定した「声(スタイル)」・トーン・誠実さのルールに沿って、
メイン投稿1件 + 連投${format.threadCount - 1}件程度のスレッドを作ってください。
各投稿は必ず${THREADS_MAX_CHARS}文字以内。ターゲットは40〜60代女性。
必ず次のJSONのみを出力してください (前後に説明文やコードブロックの記号を付けない):

{
  "text": "メイン投稿の本文 (${THREADS_MAX_CHARS}文字以内)",
  "thread": ["連投2件目の本文", "連投3件目の本文", "..."],
  "hashtags": "#ダイエット #糖質ダイエット のように1〜3個 (任意)"
}`;
}
